import { Grid, OrbitControls } from '@react-three/drei'
import { Canvas, useLoader } from '@react-three/fiber'
import { Suspense, useLayoutEffect, useRef } from 'react'
import { Box3, BoxHelper, Color, Group, Vector3 } from 'three'
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js'
import type { ChecklistState } from '../lib/types'

type Props = {
  meshSrc: string | null
  taskId: number | null
  faceCount?: number
  showCollision: boolean
  checklist: ChecklistState
}

function FittedProp({ url, showCollision }: { url: string; showCollision: boolean }) {
  const gltf = useLoader(GLTFLoader, url)
  const group = useRef<Group>(null)

  useLayoutEffect(() => {
    const g = group.current
    if (!g) return
    g.position.set(0, 0, 0)
    g.scale.set(1, 1, 1)
    g.updateWorldMatrix(true, true)
    const box = new Box3().setFromObject(g)
    const size = box.getSize(new Vector3())
    const maxDim = Math.max(size.x, size.y, size.z, 0.001)
    const scale = 1.35 / maxDim
    g.scale.setScalar(scale)
    g.updateWorldMatrix(true, true)
    const fitted = new Box3().setFromObject(g)
    const center = fitted.getCenter(new Vector3())
    g.position.x -= center.x
    g.position.z -= center.z
    g.position.y -= fitted.min.y
    g.updateWorldMatrix(true, true)

    const old = g.getObjectByName('collision-helper')
    if (old) g.remove(old)
    if (showCollision) {
      const helper = new BoxHelper(g, new Color('#e8b86d'))
      helper.name = 'collision-helper'
      g.add(helper)
    }
  }, [gltf, showCollision])

  return (
    <group ref={group}>
      <primitive object={gltf.scene} />
    </group>
  )
}

export function SceneBoard({ meshSrc, taskId, faceCount, showCollision }: Props) {
  return (
    <section className="panel">
      <h2>Scene board</h2>
      <div className="scene" data-testid="scene-board">
        {taskId ? (
          <div className="badge" data-testid="lux3d-badge">
            generated by Lux3D
          </div>
        ) : null}
        <div className="scene-canvas" data-testid="scene-canvas">
          <Canvas
            camera={{ position: [2.6, 1.7, 2.8], fov: 35, near: 0.05, far: 80 }}
            gl={{ antialias: true, alpha: false }}
            onCreated={({ camera }) => {
              camera.up.set(0, 1, 0)
              camera.lookAt(0, 0.45, 0)
            }}
          >
            <color attach="background" args={['#14170f']} />
            <hemisphereLight args={['#d7e7c8', '#2a2618', 0.85]} />
            <directionalLight position={[4, 6, 2]} intensity={1.35} />
            <directionalLight position={[-3, 2, -2]} intensity={0.35} color="#7fd1c7" />
            <Grid
              infiniteGrid
              fadeDistance={14}
              sectionColor="#4b5240"
              cellColor="#2a2e22"
              cellSize={0.25}
              sectionSize={1}
            />
            <mesh rotation={[-Math.PI / 2, 0, 0]} position={[0, 0, 0]}>
              <planeGeometry args={[18, 18]} />
              <meshStandardMaterial color="#1a1d14" roughness={0.95} metalness={0} />
            </mesh>
            <Suspense fallback={null}>
              {meshSrc ? <FittedProp url={meshSrc} showCollision={showCollision} /> : null}
            </Suspense>
            <OrbitControls makeDefault target={[0, 0.45, 0]} enableDamping />
          </Canvas>
        </div>
        <div className="hud">
          <span data-testid="asset-faces">{faceCount ? `${faceCount.toLocaleString()} faces` : 'face budget pending'}</span>
          <span>{taskId ? `lux3d · ${taskId}` : 'drop a brief to generate'}</span>
        </div>
      </div>
    </section>
  )
}
