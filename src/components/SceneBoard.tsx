import { Canvas } from '@react-three/fiber'
import { Suspense } from 'react'
import { BoothScene } from './BoothScene'
import type { BoothSlot } from '../lib/booth'
import type { JobStatus } from '../lib/types'
import { usePrefersReducedMotion } from '../hooks/usePrefersReducedMotion'

type Props = {
  meshSrc: string | null
  taskId: number | null
  faceCount?: number
  showCollision: boolean
  status: JobStatus
  slot: BoothSlot
}

export function SceneBoard({ meshSrc, taskId, faceCount, showCollision, status, slot }: Props) {
  const reducedMotion = usePrefersReducedMotion()

  return (
    <div className="scene" data-testid="scene-board">
      {taskId ? (
        <div className="badge" data-testid="lux3d-badge">
          Generated by Lux3D
        </div>
      ) : null}
      <div className="scene-canvas" data-testid="scene-canvas">
        <Canvas
          camera={{
            position: slot.cameraPosition,
            fov: 35,
            near: 0.05,
            far: 80,
          }}
          gl={{ antialias: true, alpha: false, powerPreference: 'high-performance' }}
          dpr={[1, 2]}
          onCreated={({ camera }) => {
            camera.up.set(0, 1, 0)
            camera.lookAt(...slot.cameraTarget)
          }}
        >
          <Suspense fallback={null}>
            <BoothScene
              meshSrc={meshSrc}
              slot={slot}
              status={status}
              showCollision={showCollision}
              reducedMotion={reducedMotion}
              hideStock
            />
          </Suspense>
        </Canvas>
      </div>
      <div className="hud">
        <span data-testid="asset-faces">
          {faceCount ? `${faceCount.toLocaleString()} faces requested` : 'Face budget pending'}
        </span>
        <span>{taskId ? `Lux3D task ${taskId}` : 'Write the brief against this floor'}</span>
      </div>
    </div>
  )
}
